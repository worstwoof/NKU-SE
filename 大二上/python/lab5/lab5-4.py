s1 = {32, 5, 'c', '32', '11'}
print("s1:", s1)
# 原因：集合是无序的，输出顺序可能和定义时不一致。
# 32 (整数) 和 '32' (字符串) 是不同的元素，都会保留，集合可以容纳不同类型的数据。


s2 = set({32, '46', 32, 'aa'})
print("s2:", s2)
# 原因：集合的“去重”特性。重复的 32 被自动删除了。


s3 = set('4,32,46,11,32')
print("s3:", s3)
# 原因：字符串是可迭代的，set 会遍历字符串的每一个字符。
# 结果包含了 '4', '3', '2', '6', '1' 和逗号 ','，而不是数字列表。


s4 = set([1, 2, 3])
print("s4:", s4)
# 原因：将列表转换为集合。


s5 = set((1, 2, 3))
print("s5:", s5)
# 原因：将元组转换为集合，效果和列表一样。


s6 = set({'a': 1, 'b': 2, 'c': 3})
print("s6:", s6)
# 原因：字典迭代时默认只迭代键，所以结果只有 {'a', 'b', 'c'}。